export default async function before(m, { conn, bot }) {
  if (!m.text) return false; // لو مفيش نص، اخرج

  // تحويل النص لصغير عشان البحث يبقى أدق
  const text = m.text.toLowerCase().trim();

  // --- 1. فلتر الشتائم بالأهل (الأولوية القصوى) ---
  const familyInsults = ["يا ابن", "يا بن", "امك", "ابوك", "خالتك", "اهلك", "عرضك", "اختك"];
  for (let word of familyInsults) {
    if (text.includes(word)) {
      const moralReplies = [
        "*عيب يا بابا تجيب سيرة الأهل، صلي على النبي واهدى ✨*",
        "*الأهل خط أحمر، اذكر الله وخلي لسانك نضيف 🤍*",
        "*الرجولة أدب مش قلة أدب بالأهل، صلي على الزين ✨*"
      ];
      await m.reply(moralReplies[Math.floor(Math.random() * moralReplies.length)]);
      return true; // وقف البحث هنا عشان ردينا خلاص
    }
  }

  // --- 2. فلتر الشتائم العادية والاستفزاز ---
  const insults = ["حمار", "كلب", "غبي", "وسخ", "قذر", "حيوان", "زفت", "بضان", "خرا", "انقلع", "غور", "هبل"];
  for (let word of insults) {
    if (text.includes(word)) {
      const shutUpReplies = [
        "*استهدى بالله كدا وصلي على النبي، اللسان الحلو رزق ✨*",
        "*مش هرد عليك عشان أنا بوت متربي، الله يسامحك 🤖🤍*",
        "*اذكر الله يا غالي، الكلمة الطيبة صدقة ✨*"
      ];
      await m.reply(shutUpReplies[Math.floor(Math.random() * shutUpReplies.length)]);
      return true;
    }
  }

  // --- 3. قائمة الردود الذكية (مفاتيح الكلمات) ---
  const triggers = {
    "السلام عليكم": ["*وعليكم السلام يا ريس، نورت الجروب والله ❤️*", "*وعليكم السلام، أجدع مِسا عليك ✨*"],
    "صباح الخير": ["*صباح القشطة يا عسل 🍯*", "*يا صباح الفل والياسمين 🌸*"],
    "مساء الخير": ["*أحلى مسا على عيونك يا غالي 🌙*", "*مساء الورد والجوري 🌹*"],
    "عامل ايه": ["*زي الفل طول ما أنت بخير يا شق ❤️*", "*الحمد لله، مستور وعال العال ✨*"],
    "يا اسطى": ["*قلب الأسطى، اؤمر يا شق؟ ⚡*", "*معاك يا زميلي، وش محتاج؟ ✨*"],
    "يا بوت": ["*يا نعمين، اؤمر يا باشا 🤖*", "*مين بينادي على الحريف؟ ✨*"],
    "منور": ["*النور نورك يا قلبي ✨*", "*ده نورك اللي عاكس على الجروب 🌹*"],
    "احبك": ["*وأنا أموت فيك يا رايق ❤️*", "*حبك في القلب والله ✨*"],
    "تست": ["*البوت شغال وبيمسي عليك يا بطل ✅🚀*"],
    "قوانين": ["*1. ممنوع الشتم 🚫*\n*2. ممنوع اللينكات 🔗*\n*3. احترم غيرك يحترمك ✨*"],
    "لينك": ["*خد اللينك يا وحش بس ما تدخلهوش غير المحترمين ✨*\nhttps://chat.whatsapp.com/GizaGroup"],
    "الادمن": ["*الادمن بيعمل مصلحة وهيجيلك، اهدى 😂*", "*عايز منه إيه؟ لو شكوى انسى، هو صاحبي 🤫*"],
    "صلوا على النبي": ["*اللهم صل وسلم وبارك على نبينا محمد ﷺ ✨*", "*عليه أفضل الصلاة وأتم التسليم 🤍*"],
    "جمعة مباركة": ["*علينا وعليك بالخير واليمن والبركات 🤲✨*"],
    "الحمد لله": ["*دوم يارب بخير وسعادة 🤲*"],
    "فينكم": ["*موجودين في المطبخ بنعمل شاي، تشرب؟ ☕*", "*مستنيين حد يفتح سيرة حلوة عشان نطلع 😂*"]
  };

  // البحث في الردود العادية
  for (let key in triggers) {
    if (text.includes(key)) {
      const replies = triggers[key];
      await m.reply(replies[Math.floor(Math.random() * replies.length)]);
      return true;
    }
  }

  return false;
}
