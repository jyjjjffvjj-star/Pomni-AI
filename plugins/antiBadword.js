const handler = m => m;

handler.before = async function (m, { conn, isBotAdmin, isAdmin, isOwner }) {
    if (!m.isGroup || !m.text) return;

    // استثناء المطور والادمن والبوت نفسه
    if (isOwner || isAdmin || m.fromMe) return;

    const displayImg = "https://telegra.ph/file/0c6e8f498c4d68837e28b.jpg";
    
    // فحص لو الرسالة فيها أي كلمة من "الجنازة" اللي فوق
    const isBad = badWords.some(word => m.text.toLowerCase().includes(word));

    if (isBad) {
        // 1. الحذف الفوري
        if (isBotAdmin) {
            try {
                await conn.sendMessage(m.chat, { 
                    delete: { 
                        remoteJid: m.chat, 
                        fromMe: false, 
                        id: m.key.id, 
                        participant: m.sender 
                    } 
                });
            } catch (err) {
                console.log("خطأ في حذف الشتيمة: ", err);
            }
        }

        // 2. الرد الحازم بستايل الهواري
        const warnText = `⚠️ *رادار الهواري لقط قذارة!*\n\nيا @${m.sender.split('@')[0]} ممنوع شتايم يا نرم احترم نفسك.. تم حذف رسالتك وتطهير الجروب! 🦁🛡️`;

        await conn.sendMessage(m.chat, {
            text: warnText,
            mentions: [m.sender],
            contextInfo: {
                forwardingScore: 999,
                isForwarded: true,
                externalAdReply: {
                    title: "ALHWARY BOT - Moral Shield 🛡️",
                    body: "نظام الرادار والتطهير التلقائي",
                    thumbnailUrl: displayImg,
                    mediaType: 1,
                    renderLargerThumbnail: false,
                    sourceUrl: 'https://chat.whatsapp.com/LHeUCCvuOlF8IxI4YBOYGR'
                }
            }
        });
        
        return false; // يوقف الكود هنا
    }
};

export default handler;
  
